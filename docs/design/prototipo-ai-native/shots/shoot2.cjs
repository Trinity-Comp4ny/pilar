const { chromium } = require(process.argv[2]);
const path = require('path');
const url = 'file://' + path.resolve(__dirname, '../prototipo-ai-native/index.html');
(async () => {
  const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', e => errors.push('pageerror: ' + e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
  await page.goto(url, { waitUntil: 'networkidle' });
  const go = async id => { await page.click(`.rail .ri.desk[data-go="${id}"]`); await page.waitForTimeout(450); };
  const shot = async (n, full = false) => page.screenshot({ path: path.join(__dirname, n + '.png'), fullPage: full });
  const c = async sel => { await page.click(sel); await page.waitForTimeout(350); };

  await shot('plano', true);
  await go('inicio'); await shot('inicio', true);
  await go('proposta'); await c('.step:nth-child(3)'); await page.fill('#pa', '160'); await page.waitForTimeout(200); await shot('prop-2');
  await c('.step:nth-child(5)'); await shot('prop-4a');
  await c('[data-act="negsend"]'); await c('[data-act="negaccept"]'); await shot('prop-4c');
  await go('modelos'); await c('[data-act="tpl"][data-arg="obra"]'); await shot('modelos-obra');
  await go('documentos'); await c('[data-act="scan"]'); await page.waitForTimeout(4800); await c('[data-act="scanview"][data-arg="3d"]'); await page.waitForTimeout(800); await shot('scan-3d');
  await go('obra'); await c('[data-act="andaime"][data-arg="sim"]'); await c('[data-act="clima"]'); await shot('obra-crono', true);
  await c('[data-act="obraview"][data-arg="progresso"]'); await page.waitForTimeout(800); await shot('prog-3d');
  await c('[data-act="progview"][data-arg="2d"]');
  await page.click('.plan2d line.hit[data-arg="w1"]', { force: true }); await page.waitForTimeout(300);
  await page.click('.plan2d line.hit[data-arg="w9"]', { force: true }); await page.waitForTimeout(300);
  await shot('prog-2d-sel');
  await c('[data-act="ape"][data-arg="0"]'); await c('[data-act="app"][data-arg="50"]'); await c('[data-act="apply"][data-arg="relatado"]');
  await c('[data-act="progview"][data-arg="3d"]'); await page.waitForTimeout(1900); await shot('prog-3d-applied');
  await c('[data-act="layer"][data-arg="ambientes"]'); await page.waitForTimeout(600); await shot('prog-amb');
  await page.click('[data-chk="sobrado"]'); await page.waitForTimeout(400); await c('[data-act="layer"][data-arg="estrutura"]'); await page.waitForTimeout(800); await shot('prog-estr-sobrado');
  await c('[data-act="layer"][data-arg="externo"]'); await page.waitForTimeout(800); await shot('prog-ext');
  await go('campo'); await c('[data-act="rec"]'); await page.waitForTimeout(1700); await shot('campo-rec');
  await page.waitForTimeout(3500); await shot('campo-review');
  await c('[data-act="sendrdo"]'); await page.waitForTimeout(1800); await shot('campo-sent');
  await c('[data-act="rdo"][data-arg="vago"]'); await c('[data-act="rec"]'); await page.waitForTimeout(5300); await shot('vago-review');
  await c('[data-act="aroom"][data-arg="quarto1"]'); await c('[data-act="apct"][data-arg="50"]'); await c('[data-act="apes"][data-arg="3"]'); await shot('vago-answered', true);
  await go('orcamento'); await c('[data-act="orctab"][data-arg="materiais"]'); await shot('orc-mat');
  await page.click('[data-dev="mobile"]'); await page.waitForTimeout(300);
  await page.click('.rail .ri.mob[data-go="campo"]'); await page.waitForTimeout(900); await shot('m-campo');
  await page.click('.rail .ri.mob[data-go="inicio"]'); await page.waitForTimeout(500); await shot('m-inicio');
  await page.click('.rail .ri.mob[data-go="proposta"]'); await page.waitForTimeout(500); await shot('m-proposta');
  console.log(errors.length ? errors.join('\n') : 'NO_ERRORS');
  await browser.close();
})();
